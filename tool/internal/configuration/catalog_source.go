//go:generate go run ../../cmd/gen-config-catalog -output catalog.yaml

// upstreamInstrumentation is the unmodified schema/instrumentation.yaml from
// OpenTelemetryConfigurationCommit. Keep this snapshot and the provenance in
// definitions.go together; generation and tests do not access the network.
//
//go:embed upstream-instrumentation.yaml
var upstreamInstrumentation []byte

//go:embed go-configurations.yaml
var goConfigurations []byte

type upstreamSchema struct {
	Ref             string                     `yaml:"$ref"`
	Type            yaml.Node                  `yaml:"type"`
	Description     string                     `yaml:"description"`
	DefaultBehavior string                     `yaml:"defaultBehavior"`
	Properties      map[string]*upstreamSchema `yaml:"properties"`
	Definitions     map[string]*upstreamSchema `yaml:"$defs"`
	Items           *upstreamSchema            `yaml:"items"`
}

// GenerateCatalog builds the offline catalog from the pinned general schema
// and otelc's own go.* definitions. Names are relative to the upstream
// instrumentation/development root; that root suffix is not added to leaves.
func GenerateCatalog() ([]byte, error) {
	var root upstreamSchema
	if err := yaml.Unmarshal(upstreamInstrumentation, &root); err != nil {
		return nil, ex.Wrapf(err, "parse pinned instrumentation schema")
	}
	general, ok := root.Properties["general"]
	if !ok {
		return nil, ex.New("pinned instrumentation schema has no general property")
	}
	definitions := make(map[string]Entry)
	if err := collectGeneralDefinitions(
		general,
		"general",
		root.Definitions,
		make(map[string]bool),
		definitions,
	); err != nil {
		return nil, err
	}
	owned, err := ParseMetadata(goConfigurations, "go-configurations.yaml")
	if err != nil {
		return nil, err
	}
	for _, entry := range owned.Entries {
		if entry.Ref != "" || !strings.HasPrefix(entry.Name, "go.") {
			return nil, ex.Newf("%s: otelc-owned definitions must name a go.* path directly", entry.Source)
		}
		if _, exists := definitions[entry.Name]; exists {
			return nil, ex.Newf("%s: duplicate catalog name %q", entry.Source, entry.Name)
		}
		definitions[entry.Name] = entry
	}
	document := catalogDocument{
		CatalogVersion: 1,
		Source: catalogSource{
			Repository: "open-telemetry/opentelemetry-configuration",
			Release:    OpenTelemetryConfigurationRelease,
			Commit:     OpenTelemetryConfigurationCommit,
			File:       OpenTelemetryConfigurationFile,
		},
		Definitions: definitions,
	}
	var output bytes.Buffer
	_, _ = output.WriteString(
		"# Code generated by go generate; DO NOT EDIT.\n# Source: " + OpenTelemetryConfigurationURL + "\n",
	)
	encoder := yaml.NewEncoder(&output)
	const catalogIndent = 2
	encoder.SetIndent(catalogIndent)
	if err = encoder.Encode(document); err != nil {
		return nil, ex.Wrapf(err, "encode configuration catalog")
	}
	if err = encoder.Close(); err != nil {
		return nil, ex.Wrapf(err, "close configuration catalog encoder")
	}
	return output.Bytes(), nil
}

func collectGeneralDefinitions(
	node *upstreamSchema,
	path string,
	definitions map[string]*upstreamSchema,
	active map[string]bool,
	entries map[string]Entry,
) error {
	if node.Ref != "" {
		if !strings.HasPrefix(node.Ref, "#/$defs/") || active[node.Ref] {
			return ex.Newf("%s: unsupported or cyclic schema reference %q", path, node.Ref)
		}
		target, ok := definitions[strings.TrimPrefix(node.Ref, "#/$defs/")]
		if !ok {
			return ex.Newf("%s: unknown schema reference %q", path, node.Ref)
		}
		active[node.Ref] = true
		err := collectGeneralDefinitions(target, path, definitions, active, entries)
		delete(active, node.Ref)
		return err
	}
	if len(node.Properties) > 0 {
		keys := make([]string, 0, len(node.Properties))
		for key := range node.Properties {
			keys = append(keys, key)
		}
		slices.Sort(keys)
		for _, key := range keys {
			if err := collectGeneralDefinitions(
				node.Properties[key],
				path+"."+key,
				definitions,
				active,
				entries,
			); err != nil {
				return err
			}
		}
		return nil
	}
	typeName, err := upstreamType(node.Type)
	if err != nil {
		return ex.Wrapf(err, "%s", path)
	}
	switch typeName {
	case "integer":
		typeName = integerType
	case "array":
		if node.Items == nil || node.Items.Type.Value != stringType {
			return ex.Newf("%s: pinned array must have string items", path)
		}
		typeName = listType
	case booleanType, stringType:
	default:
		return ex.Newf("%s: unsupported upstream leaf type %q", path, typeName)
	}
	entries[path] = Entry{
		Name: path, Type: typeName,
		Description:     strings.TrimSpace(node.Description),
		DefaultBehavior: strings.TrimSpace(node.DefaultBehavior),
	}
	return nil
}

func upstreamType(node yaml.Node) (string, error) {
	if node.Kind == yaml.ScalarNode && node.Tag == yamlStringTag {
		return node.Value, nil
	}
	if node.Kind != yaml.SequenceNode {
		return "", ex.New("upstream type must be a string or a nullable type union")
	}
	var result string
	for _, child := range node.Content {
		if child.Value == "null" {
			continue
		}
		if result != "" {
			return "", ex.New("upstream union must contain only one non-null type")
		}
		result = child.Value
	}
	if result == "" {
		return "", ex.New("upstream type must not be null-only")
	}
	return result, nil
}
