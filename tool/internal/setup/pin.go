func removeImports(f *dst.File, importPaths map[string]bool) error {
	decls := make([]dst.Decl, 0, len(f.Decls))

	for _, decl := range f.Decls {
		genDecl, isGenDecl := decl.(*dst.GenDecl)
		if !isGenDecl || genDecl.Tok != token.IMPORT {
			decls = append(decls, decl)
			continue
		}

		specs := genDecl.Specs[:0]
		for _, spec := range genDecl.Specs {
			importSpec, isImportSpec := spec.(*dst.ImportSpec)
			if !isImportSpec {
				specs = append(specs, spec)
				continue
			}

			path, err := strconv.Unquote(importSpec.Path.Value)
			if err != nil {
				return ex.Wrapf(err, "failed to unquote import path %s", importSpec.Path.Value)
			}

			// skip the import we want to remove
			if _, removeImport := importPaths[path]; removeImport {
				continue
			}

			specs = append(specs, spec)
		}

		if len(specs) == 0 {
			// entire import decl became empty
			continue
		}

		genDecl.Specs = specs
		decls = append(decls, genDecl)
	}

	f.Decls = decls
	return nil
}

func generateDirective(opts PinOptions) string {
	args := []string{
		"//go:generate",
		"go",
		"tool",
		util.OtelcToolExe,
		"pin",
		"--generate",
	}

	if !opts.Prune {
		args = append(args, "--prune=false")
	}
	if opts.Validate {
		args = append(args, "--validate")
	}

	return strings.Join(args, " ")
}

func updateGenerateDirective(f *dst.File, opts PinOptions) {
	// Nothing passed? Do not touch the directive at all.
	if opts.Generate == nil {
		return
	}

	comments := make([]string, 0, len(f.Decs.Start.All()))
	for _, comment := range f.Decs.Start.All() {
		// Drop any existing otelc pin directive. We will either
		// regenerate it or remove it entirely.
		const goGenerateDirectivePrefix = "//go:generate go tool " + util.OtelcToolExe + " pin"
		if strings.HasPrefix(comment, goGenerateDirectivePrefix) {
			continue
		}

		comments = append(comments, comment)
	}

	if *opts.Generate {
		comments = append(comments, generateDirective(opts))
	}

	f.Decs.Start.Clear()
	f.Decs.Start.Append(comments...)
}

func generateOtelInstrumentationGo(imports map[string]bool, opts PinOptions) *dst.File {
	// Create a slice of import paths and sort them
	importPaths := slices.Sorted(maps.Keys(imports))

	// Use the sorted import paths to create import specs
	importSpecs := make([]dst.Spec, 0, len(importPaths))
	for _, path := range importPaths {
		importSpecs = append(importSpecs, &dst.ImportSpec{
			Name: ast.Ident(ast.IdentIgnore),
			Path: &dst.BasicLit{
				Kind:  token.STRING,
				Value: strconv.Quote(path),
			},
		})
	}

	comments := ast.LineComments(
		"// This file is automatically generated by otelc pin for tracking instrumentations.",
		"// Additional instrumentation imports may be added manually.",
		"\n",
		"//go:build tools",
	)

	// If generate is explicitly enabled, or not set at all, include the //go:generate directive.
	if opts.Generate == nil || *opts.Generate {
		comments.Start.Append(generateDirective(opts))
	}

	f := &dst.File{
		Name: ast.Ident("tools"),
		Decs: dst.FileDecorations{
			NodeDecs: comments,
		},
	}
	if len(importSpecs) > 0 {
		f.Decls = []dst.Decl{&dst.GenDecl{Tok: token.IMPORT, Specs: importSpecs}}
	}
	return f
}

type otelYAMLConfig struct {
	Instrumentations []string `yaml:"instrumentations"`
}

func loadOtelYAMLImports(path string) (map[string]bool, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, ex.Wrapf(err, "reading %s", path)
	}

	var cfg otelYAMLConfig
	decoder := yaml.NewDecoder(strings.NewReader(string(data)))
	decoder.KnownFields(true)
	if err = decoder.Decode(&cfg); err != nil && !errors.Is(err, io.EOF) {
		return nil, ex.Wrapf(err, "parsing %s", path)
	}
	for {
		var extra any
		err = decoder.Decode(&extra)
		if errors.Is(err, io.EOF) {
			break
		}
		if err != nil {
			return nil, ex.Wrapf(err, "parsing %s", path)
		}
		// A trailing document separator and comments form an empty YAML
		// document (decoded as nil). Allow those, but reject any later
		// populated document as well as malformed YAML after an empty one.
		if extra != nil {
			return nil, ex.Newf("%s: multiple YAML documents are not allowed", path)
		}
	}

	imports := make(map[string]bool, len(cfg.Instrumentations))
	for _, importPath := range cfg.Instrumentations {
		importPath = strings.TrimSpace(importPath)
		if importPath == "" {
			return nil, ex.Newf("%s: instrumentations must not contain empty import paths", path)
		}
		imports[importPath] = true
	}
	return imports, nil
}

func writeOtelYAMLImports(path string, imports map[string]bool) error {
	currentImports, err := loadOtelYAMLImports(path)
	if err != nil {
		return err
	}
	if maps.Equal(currentImports, imports) {
		return nil
	}

	data, err := os.ReadFile(path)
	if err != nil {
		return ex.Wrapf(err, "reading %s", path)
	}
	info, err := os.Stat(path)
	if err != nil {
		return ex.Wrapf(err, "stating %s", path)
	}

	var document yaml.Node
	decoder := yaml.NewDecoder(bytes.NewReader(data))
	if err = decoder.Decode(&document); err != nil {
		return ex.Wrapf(err, "parsing %s", path)
	}
	root := &document
	if root.Kind == yaml.DocumentNode {
		if len(root.Content) == 0 {
			return nil
		}
		root = root.Content[0]
	}
	if root.Kind != yaml.MappingNode {
		return ex.Newf("%s: expected a YAML mapping", path)
	}

	var sequence *yaml.Node
	for i := 0; i+1 < len(root.Content); i += 2 {
		if root.Content[i].Value == "instrumentations" {
			sequence = root.Content[i+1]
			break
		}
	}
	if sequence == nil || sequence.Tag == "!!null" {
		return nil
	}
	if sequence.Kind != yaml.SequenceNode {
		return ex.Newf("%s: instrumentations must be a YAML sequence", path)
	}

	current := make(map[string]bool, len(sequence.Content))
	for _, node := range sequence.Content {
		current[strings.TrimSpace(node.Value)] = true
	}
	if maps.Equal(current, imports) {
		return nil
	}

	kept := sequence.Content[:0]
	for _, node := range sequence.Content {
		if imports[strings.TrimSpace(node.Value)] {
			kept = append(kept, node)
		}
	}
	sequence.Content = kept

	data, err = yaml.Marshal(&document)
	if err != nil {
		return ex.Wrapf(err, "marshalling %s", path)
	}
	if err = util.WriteFileAtomic(path, data, info.Mode().Perm()); err != nil {
		return ex.Wrapf(err, "writing %s", path)
	}
	return nil
}

type yamlRule struct {
	Target       rule.Target `yaml:"target"`
	VersionRange string      `yaml:"version"`
}

func loadModuleRules(
	ctx context.Context,
	moduleDir, module, currentVersion string,
	loaded map[string][]yamlRule,
) error {
	return filepath.WalkDir(moduleDir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return ex.Wrap(err)
		}

		if d.IsDir() {
			// Skip any submodules
			if path != moduleDir && util.PathExists(filepath.Join(path, goModFileName)) {
				return filepath.SkipDir
			}
			return nil
		}

		if !util.IsRuleFile(d.Name()) {
			return nil
		}

		data, readErr := os.ReadFile(path) //nolint:gosec // walking rules from the source checkout
		if readErr != nil {
			return ex.Wrapf(readErr, "reading rule file %s", path)
		}

		doc, parseErr := rule.ParseFile(data)
		if parseErr != nil {
			return ex.Wrapf(parseErr, "parsing rule file %s", path)
		}
		if versionErr := checkRuleFileVersion(ctx, path, doc, currentVersion); versionErr != nil {
			return versionErr
		}

		for _, entry := range doc.Entries {
			var r yamlRule
			if decodeErr := entry.Node.Decode(&r); decodeErr != nil {
				return ex.Wrapf(decodeErr, "parsing rule %q in %s", entry.Name, path)
			}
			if r.Target.IsZero() {
				continue
			}
			if validateErr := r.Target.Validate(); validateErr != nil {
				return ex.Wrapf(validateErr, "validating target for rule %q in %s", entry.Name, path)
			}
			loaded[module] = append(loaded[module], r)
		}

		return nil
	})
}

func loadMinimalRules(
	ctx context.Context,
	rulesRoot, currentVersion string,
) (map[string][]yamlRule, error) {
	loaded := make(map[string][]yamlRule)

	err := filepath.WalkDir(rulesRoot, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return ex.Wrap(err)
		}
		// rulesRoot is instrumentation/
		// We want to load rules for submodules within instrumentation/
		// Look for go.mod nested within instrumentation/
		if d.IsDir() || d.Name() != goModFileName || filepath.Dir(path) == rulesRoot {
			return nil
		}

		modFile, err := parseGoMod(path)
		if err != nil {
			return ex.Wrapf(err, "loading %s", path)
		}

		return loadModuleRules(ctx, filepath.Dir(path), modFile.Module.Mod.Path, currentVersion, loaded)
	})
	if err != nil {
		return nil, err
	}

	return loaded, nil
}

func ensureOtelcRequireVersion(f *modfile.File, version string) (bool, error) {
	if !semver.IsValid(version) || version == "v0.0.0" || module.IsPseudoVersion(version) {
		return false, nil
	}

	for _, req := range f.Require {
		if req.Mod.Path != util.OtelcRoot {
			continue
		}

		if semver.Compare(req.Mod.Version, version) >= 0 {
			return false, nil
		}
		break
	}

	if err := f.AddRequire(util.OtelcRoot, version); err != nil {
		return false, ex.Wrap(err)
	}

	return true, nil
}

func ensureOtelcRequire(moduleDir, version string) (bool, error) {
	goModPath := filepath.Join(moduleDir, goModFileName)
	data, err := os.ReadFile(goModPath)
	if err != nil {
		return false, ex.Wrap(err)
	}

	f, err := modfile.Parse(goModPath, data, nil)
	if err != nil {
		return false, ex.Wrap(err)
	}

	modified := false

	hasTool := false
	for _, tool := range f.Tool {
		if tool.Path == util.OtelcToolCmdRoot {
			hasTool = true
			break
		}
	}

	hasRequire := false
	for _, req := range f.Require {
		if req.Mod.Path == util.OtelcRoot {
			hasRequire = true
			break
		}
	}

	if !hasTool {
		if addErr := f.AddTool(util.OtelcToolCmdRoot); addErr != nil {
			return false, ex.Wrap(addErr)
		}
		modified = true
	}

	added, ensureErr := ensureOtelcRequireVersion(f, version)
	if ensureErr != nil {
		return false, ensureErr
	}
	modified = modified || added

	// Dev builds can't pin their own version, so a missing require stays
	// missing. Report it anyway so the caller tidies and go resolves one.
	if !modified {
		return !hasRequire, nil
	}

	if writeErr := writeGoMod(goModPath, f); writeErr != nil {
		return false, writeErr
	}

	return true, nil
}

func matchInstrumentationImports(
	deps []*Dependency,
	ruleset map[string][]yamlRule,
	warn func(msg string, args ...any),
) map[string]bool {
	imports := make(map[string]bool)

	// Record the first unresolved-version skip per instrumentation module.
	// Warnings are emitted after matching so we only complain when the module
	// was not imported by any other rule/dep (avoids false positives).
	skipped := make(map[string]unresolvedSkip)

	// Match only on target + version.
	for _, dep := range deps {
		for modPath, rules := range ruleset {
			for _, r := range rules {
				tm := instrumentationRuleMatchesDep(dep, r)
				if tm.isRoot {
					// always add root targets; they are further matched in setup
					imports[modPath] = true
					continue
				}
				if !tm.matched {
					continue
				}

				if !util.VersionInRange(dep.Version, r.VersionRange) {
					recordUnresolvedSkip(skipped, modPath, dep, r.VersionRange)
					continue
				}

				imports[modPath] = true
			}
		}
	}

	emitUnresolvedSkipWarnings(warn, imports, skipped)
	return imports
}

type unresolvedSkip struct {
	dep          string
	versionRange string
}

type instrumentationTargetMatch struct {
	matched bool
	isRoot  bool
}

// instrumentationRuleMatchesDep reports whether r's target matches dep.
// Targets that include $root always pin the instrumentation module; setup
// matches them precisely later. Other targets are matched without the root
// module paths, so an excluded $root excludes nothing here, which can only
// pin a module that setup then leaves unused.
func instrumentationRuleMatchesDep(dep *Dependency, r yamlRule) instrumentationTargetMatch {
	if r.Target.IncludesRoot() {
		return instrumentationTargetMatch{matched: true, isRoot: true}
	}
	return instrumentationTargetMatch{matched: r.Target.Matches(dep.ImportPath, nil)}
}

func recordUnresolvedSkip(
	skipped map[string]unresolvedSkip,
	modPath string,
	dep *Dependency,
	versionRange string,
) {
	if !unresolvedVersionSkip(dep.Version, versionRange) {
		return
	}
	if _, ok := skipped[modPath]; ok {
		return
	}
	skipped[modPath] = unresolvedSkip{
		dep:          dep.ImportPath,
		versionRange: versionRange,
	}
}

func emitUnresolvedSkipWarnings(
	warn func(msg string, args ...any),
	imports map[string]bool,
	skipped map[string]unresolvedSkip,
) {
	if warn == nil {
		return
	}
	for modPath, s := range skipped {
		if imports[modPath] {
			continue
		}
		warnUnresolvedVersionSkip(warn, s.dep, s.versionRange,
			"instrumentation", modPath,
		)
	}
}

// skipTidyMessage is logged when updateToolFile skips go mod tidy. Tests match
// on it, since a skipped tidy leaves nothing else behind.
const skipTidyMessage = "tool file and go.mod unchanged, skipping go mod tidy"

func updateToolFile(ctx context.Context, toolFile string, prunedImports map[string]bool, opts PinOptions) error {
	original, readErr := os.ReadFile(toolFile)
	if readErr != nil {
		return ex.Wrap(readErr)
	}

	p := ast.NewAstParser()

	f, parseErr := p.Parse(toolFile, parser.ParseComments)
	if parseErr != nil {
		return parseErr
	}

	if len(prunedImports) > 0 {
		if removeErr := removeImports(f, prunedImports); removeErr != nil {
			return removeErr
		}
	}

	updateGenerateDirective(f, opts)

	updated, printErr := ast.RenderFile(f)
	if printErr != nil {
		return printErr
	}

	toolFileChanged := !bytes.Equal(updated, original)
	if toolFileChanged {
		if writeErr := util.WriteFileAtomic(toolFile, updated); writeErr != nil {
			return writeErr
		}
	}

	goModChanged, ensureErr := ensureOtelcRequire(filepath.Dir(toolFile), util.Version)
	if ensureErr != nil {
		return ensureErr
	}

	// go mod tidy loads the whole module graph, so only run it when otelc
	// changed the tool file or go.mod, or go.sum is missing. Manual go.mod
	// edits are left for the user to tidy.
	goSumPath := filepath.Join(filepath.Dir(toolFile), "go.sum")
	if !toolFileChanged && !goModChanged && util.PathExists(goSumPath) {
		util.LoggerFromContext(ctx).DebugContext(ctx, skipTidyMessage, "toolFile", toolFile)
		return nil
	}

	return runModTidy(ctx, filepath.Dir(toolFile))
}

func validateRuleFiles(ctx context.Context, ruleFiles []string) error {
	for _, ruleFile := range ruleFiles {
		content, err := os.ReadFile(ruleFile)
		if err != nil {
			return ex.Wrapf(err, "reading %s", ruleFile)
		}
		doc, err := rule.ParseFile(content)
		if err != nil {
			return ex.Wrapf(err, "parsing rule file %s", ruleFile)
		}
		if err = checkRuleFileVersion(ctx, ruleFile, doc, util.Version); err != nil {
			return err
		}
		if _, err = doc.Rules(); err != nil {
			return err
		}
	}
	return nil
}

func updatePinnedProjects(
	ctx context.Context,
	toolFiles []string,
	opts PinOptions,
) error {
	prunedImports, err := invalidInstrumentationImports(ctx, toolFiles, opts.Validate, opts.Prune)
	if err != nil {
		return err
	}

	for _, toolFile := range toolFiles {
		if updateErr := updateToolFile(ctx, toolFile, prunedImports[toolFile], opts); updateErr != nil {
			return updateErr
		}
	}

	return nil
}

type modulePinConfig struct {
	moduleDir string
	toolFile  string
	yamlFile  string
}

type yamlPinState struct {
	config          modulePinConfig
	imports         map[string]bool
	originalImports map[string]bool
	toolFile        string
}

func loadYAMLStates(configs []modulePinConfig) ([]yamlPinState, error) {
	states := make([]yamlPinState, 0, len(configs))
	for _, config := range configs {
		imports, err := loadOtelYAMLImports(config.yamlFile)
		if err != nil {
			return nil, err
		}
		states = append(states, yamlPinState{
			config:          config,
			imports:         imports,
			originalImports: maps.Clone(imports),
		})
	}
	return states, nil
}

func yamlStateManager(ctx context.Context, autoPin bool) (*stateManager, error) {
	if !autoPin {
		return newStateManager(), nil
	}
	manager, found := stateManagerFromContext(ctx)
	if !found {
		return nil, ex.New("state manager not found in context")
	}
	return manager, nil
}

func trackYAMLConfigFiles(
	ctx context.Context,
	manager *stateManager,
	configs []modulePinConfig,
	opts PinOptions,
) error {
	moduleDirs := make([]string, 0, len(configs))
	for _, config := range configs {
		moduleDirs = append(moduleDirs, config.moduleDir)
	}
	files, err := getBackupFiles(ctx, buildDir(opts.Subcommand, opts.Args), normalizeModuleDirs(moduleDirs))
	if err != nil {
		return err
	}
	return manager.TrackAll(files...)
}

func pruneYAMLStates(states []yamlPinState, invalid map[string]map[string]bool) {
	for i := range states {
		for importPath := range invalid[states[i].toolFile] {
			delete(states[i].imports, importPath)
		}
	}
}

func rollbackYAMLState(err error, manager *stateManager, autoPin bool) error {
	if autoPin {
		// The build lifecycle owns AutoPin state and will restore it through
		// Cleanup after this error returns.
		return err
	}
	if revertErr := manager.Revert(); revertErr != nil {
		return ex.Join(err, ex.Wrapf(revertErr, "restoring files after failed otelc pin"))
	}
	if discardErr := manager.Discard(); discardErr != nil {
		return ex.Join(err, ex.Wrapf(discardErr, "discarding restored otelc pin state"))
	}
	return err
}

func finalizeAutoPinYAML(ctx context.Context, states []yamlPinState, opts PinOptions) error {
	for _, state := range states {
		if err := ast.WriteFileAtomic(state.toolFile, generateOtelInstrumentationGo(state.imports, opts)); err != nil {
			return ex.Wrapf(err, "writing %s", state.toolFile)
		}
		keepForDebug(ctx, state.toolFile, "")
		// Materialization already tidied non-empty selections. Only tidy again
		// when pruning changed the tool file or when an empty selection skipped
		// dependency synchronization entirely.
		if len(state.imports) == 0 || !maps.Equal(state.imports, state.originalImports) {
			if err := runModTidy(ctx, state.config.moduleDir); err != nil {
				return ex.Wrapf(err, "running go mod tidy in %s", state.config.moduleDir)
			}
		}
	}
	return nil
}

func finalizeStandaloneYAML(states []yamlPinState, opts PinOptions, manager *stateManager) error {
	if err := manager.Revert(); err != nil {
		return err
	}
	if err := manager.Discard(); err != nil {
		return err
	}
	if !opts.Prune {
		return nil
	}
	for _, state := range states {
		if err := writeOtelYAMLImports(state.config.yamlFile, state.imports); err != nil {
			return err
		}
	}
	return nil
}

func materializeYAMLConfigs(ctx context.Context, configs []modulePinConfig, opts PinOptions) ([]string, error) {
	toolFiles := make([]string, 0, len(configs))
	for _, config := range configs {
		imports, err := loadOtelYAMLImports(config.yamlFile)
		if err != nil {
			return nil, err
		}
		toolFile := filepath.Join(config.moduleDir, toolFileCanonical)
		if err = ast.WriteFileAtomic(toolFile, generateOtelInstrumentationGo(imports, opts)); err != nil {
			return nil, ex.Wrapf(err, "writing %s", toolFile)
		}
		if _, err = ensureOtelcRequire(config.moduleDir, util.Version); err != nil {
			return nil, ex.Wrapf(err, "ensuring otelc require in go.mod in %s", config.moduleDir)
		}
		if err = syncDeps(ctx, imports, config.moduleDir); err != nil {
			return nil, ex.Wrapf(err, "syncing dependencies in %s", config.moduleDir)
		}
		toolFiles = append(toolFiles, toolFile)
	}
	return toolFiles, nil
}

func invalidInstrumentationImports(
	ctx context.Context,
	toolFiles []string,
	validate bool,
	prune bool,
) (map[string]map[string]bool, error) {
	invalid := make(map[string]map[string]bool, len(toolFiles))
	err := walkInstrumentation(ctx, toolFiles, func(v *instrumentationVisit) (bool, error) {
		var reason error
		if v.Config.Error != nil {
			if !errors.Is(v.Config.Error, errNotInstrumentation) {
				return false, v.Config.Error
			}
			reason = v.Config.Error
		} else if validate {
			if validateErr := validateRuleFiles(ctx, v.Config.RuleFiles); validateErr != nil {
				reason = validateErr
			}
		}
		if reason == nil {
			return true, nil
		}
		util.LoggerFromContext(ctx).WarnContext(ctx, "invalid instrumentation import",
			"importPath", v.Config.ImportPath, "toolFile", v.ToolFile, "reason", reason)
		_, _ = fmt.Fprintf(os.Stderr, "Invalid instrumentation import %s from %s: %v\n",
			v.Config.ImportPath, v.ToolFile, reason)
		if prune && slices.Contains(toolFiles, v.ToolFile) {
			if invalid[v.ToolFile] == nil {
				invalid[v.ToolFile] = make(map[string]bool)
			}
			invalid[v.ToolFile][v.Config.ImportPath] = true
		}
		return false, nil
	})
	return invalid, err
}

func processYAMLConfigs(ctx context.Context, configs []modulePinConfig, opts PinOptions) error {
	states, err := loadYAMLStates(configs)
	if err != nil {
		return err
	}
	if !opts.AutoPin {
		if interruptedErr := checkInterruptedBuild(); interruptedErr != nil {
			return interruptedErr
		}
	}
	manager, err := yamlStateManager(ctx, opts.AutoPin)
	if err != nil {
		return err
	}
	if err = trackYAMLConfigFiles(ctx, manager, configs, opts); err != nil {
		return rollbackYAMLState(err, manager, opts.AutoPin)
	}

	toolFiles, err := materializeYAMLConfigs(ctx, configs, opts)
	if err != nil {
		return rollbackYAMLState(err, manager, opts.AutoPin)
	}
	for i := range states {
		states[i].toolFile = toolFiles[i]
	}
	invalid, err := invalidInstrumentationImports(ctx, toolFiles, opts.Validate, opts.Prune)
	if err != nil {
		return rollbackYAMLState(err, manager, opts.AutoPin)
	}
	if opts.Prune {
		pruneYAMLStates(states, invalid)
	}
	if opts.AutoPin {
		return finalizeAutoPinYAML(ctx, states, opts)
	}
	for _, state := range states {
		generated := generateOtelInstrumentationGo(state.imports, opts)
		if writeErr := ast.WriteFileAtomic(state.toolFile, generated); writeErr != nil {
			return rollbackYAMLState(ex.Wrapf(writeErr, "writing %s", state.toolFile), manager, false)
		}
		keepForDebug(ctx, state.toolFile, "")
	}
	return finalizeStandaloneYAML(states, opts, manager)
}

func discoverPinConfigs(moduleDirs []string) ([]modulePinConfig, map[string]bool, error) {
	moduleDirs = normalizeModuleDirs(moduleDirs)
	configs := make([]modulePinConfig, 0, len(moduleDirs))
	unconfigured := make(map[string]bool)
	for _, moduleDir := range moduleDirs {
		toolFile, err := findToolFile(moduleDir)
		if err != nil {
			return nil, nil, err
		}
		if toolFile != "" {
			configs = append(configs, modulePinConfig{moduleDir: moduleDir, toolFile: toolFile})
			continue
		}
		yamlFile, err := findInstrumentationYAMLFile(moduleDir)
		if err != nil {
			return nil, nil, err
		}
		if yamlFile == "" {
			unconfigured[moduleDir] = true
			continue
		}
		configs = append(configs, modulePinConfig{moduleDir: moduleDir, yamlFile: yamlFile})
	}
	return configs, unconfigured, nil
}

func loadManifestRules() (map[string][]yamlRule, error) {
	entries, err := manifest.Load()
	if err != nil {
		return nil, ex.Wrapf(err, "loading instrumentation manifest")
	}
	ruleset := make(map[string][]yamlRule, len(entries))
	for _, entry := range entries {
		ruleset[entry.ModulePath] = append(ruleset[entry.ModulePath], yamlRule{
			Target:       rule.NewTarget(entry.Target),
			VersionRange: entry.VersionRange,
		})
	}
	return ruleset, nil
}

func generatePinnedProjects(ctx context.Context, moduleDirs []string, opts PinOptions) (*PinResult, error) {
	logger := util.LoggerFromContext(ctx)
	subcommand := opts.Subcommand
	if subcommand == "" {
		subcommand = subcmdBuild
	}

	// No tool file found? Try generating one.
	var deps []*Dependency
	if cached, ok := ctx.Value(pinDepsKey{}).(*pinDepsCache); ok && cached.loaded {
		deps = cached.deps
	} else {
		var findDepsErr error
		deps, findDepsErr = findDeps(ctx, subcommand, opts.Args)
		if findDepsErr != nil {
			return nil, findDepsErr
		}
	}

	ruleset, err := loadManifestRules()
	if err != nil {
		return nil, err
	}

	// We expect every built-in instrumentation module to be importable
	imports := matchInstrumentationImports(deps, ruleset, func(msg string, args ...any) {
		logger.WarnContext(ctx, msg, args...)
	})

	// Nothing to instrument? Warn and skip generating tool file.
	if len(imports) == 0 {
		_, _ = fmt.Fprintf(
			os.Stderr,
			"Warning: no instrumentations matched, checked %d dependencies. Skipping generating %s file.\n",
			len(deps),
			toolFileCanonical,
		)
		logger.WarnContext(ctx, "no instrumentations matched, skipping generating tool file")

		// Ok to re-use deps here, because we do not run "go mod tidy".
		return &PinResult{AllDeps: deps}, nil
	}

	// Generate otel.instrumentation.go file with imports for all matched rules.
	f := generateOtelInstrumentationGo(imports, opts)
	for _, moduleDir := range normalizeModuleDirs(moduleDirs) {
		path := filepath.Join(moduleDir, toolFileCanonical)
		if writeErr := ast.WriteFileAtomic(path, f); writeErr != nil {
			return nil, ex.Wrapf(writeErr, "writing %s", path)
		}

		if _, ensureErr := ensureOtelcRequire(moduleDir, util.Version); ensureErr != nil {
			return nil, ensureErr
		}

		if syncErr := syncDeps(ctx, imports, moduleDir); syncErr != nil {
			return nil, syncErr
		}

		keepForDebug(ctx, path, "")
	}

	// Intentionally return an empty PinResult
	// Since we ran syncDeps, the dependencies may have been updated
	// Therefore, we want to ensure we rerun findDeps in setup phase.
	return &PinResult{}, nil
}

func prepareVendoredBuild(
	ctx context.Context,
	logger *slog.Logger,
	subcommand string,
	args []string,
) ([]string, error) {
	if !vendoringActive(ctx, buildDir(subcommand, args)) {
		return args, nil
	}

	logger.InfoContext(ctx, "vendored project detected; building with -mod=mod")

	if err := os.Setenv("GOFLAGS", forceModMod(os.Getenv("GOFLAGS"))); err != nil {
		return nil, ex.Wrapf(err, "forcing module mode for vendored build")
	}

	return rewriteModVendor(subcommand, args), nil
}

type PinOptions struct {
	// Whether to prune invalid selections from the active tool or YAML configuration.
	Prune bool
	// Whether to validate that all selected instrumentation packages contain valid rules.
	Validate bool
	// Whether to have a //go:generate directive in otel.instrumentation.go
	Generate *bool
	// Args passed to go build/install/test in findDeps
	Args []string
	// Subcommand passed to go in findDeps (defaults to "build")
	Subcommand string
	// ModuleDirs lists the module directories to search for configuration files.
	// Pin normalizes duplicates and ordering; an empty list is discovered from Args.
	ModuleDirs []string
	// AutoPin reports that Pin is running as part of the clean-room build flow.
	AutoPin bool
}

type PinResult struct {
	// AllDeps is a list of all dependencies found in the project (not just those with instrumentation).
	// It may not be always present, this can be used by later stages (setup) instead of
	// re-parsing compile commands again.
	AllDeps []*Dependency
}

type pinDepsKey struct{}

type pinDepsCache struct {
	deps   []*Dependency
	loaded bool
}

// preflightPinSource validates discovery requirements before tracking or
// modifying module files. An unconfigured module needs the checkout only if
// one of its dependencies actually matches a built-in instrumentation.
func preflightPinSource(
	ctx context.Context,
	configs []modulePinConfig,
	unconfigured map[string]bool,
	opts PinOptions,
) error {
	for _, config := range configs {
		if config.yamlFile == "" {
			continue
		}
		imports, err := loadOtelYAMLImports(config.yamlFile)
		if err != nil {
			return err
		}
		if len(imports) > 0 {
			if _, err = pinSourceRoot(ctx); err != nil {
				return err
			}
		}
	}
	if len(unconfigured) == 0 {
		return nil
	}
	cache, ok := ctx.Value(pinDepsKey{}).(*pinDepsCache)
	if !ok {
		return ex.New("pin dependency cache not found in context")
	}
	if !cache.loaded {
		// findDeps writes its build plan log in this directory.
		if err := os.MkdirAll(util.GetBuildTempDir(), 0o755); err != nil {
			return ex.Wrapf(err, "creating build working directory")
		}
		subcommand := opts.Subcommand
		if subcommand == "" {
			subcommand = subcmdBuild
		}
		deps, err := findDeps(ctx, subcommand, opts.Args)
		if err != nil {
			return err
		}
		cache.deps, cache.loaded = deps, true
	}
	ruleset, err := loadManifestRules()
	if err != nil {
		return err
	}
	if len(matchInstrumentationImports(cache.deps, ruleset, nil)) > 0 {
		_, err = pinSourceRoot(ctx)
	}
	return err
}

func withPinDiscoveryCache(ctx context.Context) context.Context {
	if ctx.Value(pinSourceRootKey{}) == nil {
		ctx = context.WithValue(ctx, pinSourceRootKey{}, &pinSourceRootCache{})
	}
	if ctx.Value(pinDepsKey{}) == nil {
		ctx = context.WithValue(ctx, pinDepsKey{}, &pinDepsCache{})
	}
	return ctx
}

// Pin generates or updates otel.instrumentation.go to pin instrumentation packages for the current module.
// It also returns a PinResult, which may optionally include a list of all dependencies found in the project
// (not just those with instrumentation). The PinResult can be used by later stages (setup) instead of
// re-parsing compile commands again.
func Pin(ctx context.Context, opts PinOptions) (*PinResult, error) {
	var result *PinResult
	dir, _ := leadingDirFlag(opts.Args)
	err := withBuildLock(ctx, dir, func(ctx context.Context) error {
		if !opts.AutoPin {
			if err := checkInterruptedBuild(); err != nil {
				return err
			}
		}
		var pinErr error
		result, pinErr = pinLocked(ctx, opts)
		return pinErr
	})
	return result, err
}

func pinLocked(ctx context.Context, opts PinOptions) (*PinResult, error) {
	ctx = withPinDiscoveryCache(ctx)
	moduleDirs := normalizeModuleDirs(opts.ModuleDirs)
	// moduleDirs being empty means Pin was invoked as a standalone command
	// (not as part of a setup run), so use opts.Args to find module directories.
	if len(moduleDirs) == 0 {
		subcommand := opts.Subcommand
		if subcommand == "" {
			subcommand = subcmdBuild
		}
		// For same reason as Setup, we have to check vendoring state before
		// forcing module mode and rewriting vendor/ paths to module mode.
		args, err := prepareVendoredBuild(ctx, util.LoggerFromContext(ctx), subcommand, opts.Args)
		if err != nil {
			return nil, err
		}
		opts.Args = args

		// Use opts.Args to find module directories
		moduleDirs, err = findBuildModuleDirs(ctx, subcommand, opts.Args)
		if err != nil {
			return nil, err
		}
	}

	configs, unconfigured, err := discoverPinConfigs(moduleDirs)
	if err != nil {
		return nil, err
	}
	if err = preflightPinSource(ctx, configs, unconfigured, opts); err != nil {
		return nil, err
	}
	if err = processConfiguredModules(ctx, configs, opts); err != nil {
		return nil, err
	}
	if len(unconfigured) == 0 {
		return &PinResult{}, nil
	}

	result, err := generatePinnedProjects(ctx, slices.Sorted(maps.Keys(unconfigured)), opts)
	if err != nil {
		return nil, err
	}
	if len(configs) > 0 {
		// Configured modules may have changed dependencies, so setup must
		// rediscover them instead of reusing the pre-materialization result.
		return &PinResult{}, nil
	}
	return result, nil
}

func partitionPinConfigs(configs []modulePinConfig) ([]string, []modulePinConfig) {
	toolFiles := make([]string, 0, len(configs))
	yamlConfigs := make([]modulePinConfig, 0, len(configs))
	for _, config := range configs {
		if config.toolFile != "" {
			toolFiles = append(toolFiles, config.toolFile)
		} else {
			yamlConfigs = append(yamlConfigs, config)
		}
	}
	return toolFiles, yamlConfigs
}

func processConfiguredModules(ctx context.Context, configs []modulePinConfig, opts PinOptions) error {
	toolFiles, yamlConfigs := partitionPinConfigs(configs)
	if len(toolFiles) > 0 {
		if err := updatePinnedProjects(ctx, toolFiles, opts); err != nil {
			return err
		}
	}
	if len(yamlConfigs) > 0 {
		return processYAMLConfigs(ctx, yamlConfigs, opts)
	}
	return nil
}

// autoPin is a convenience function that automatically tracks generated/modified files before calling Pin
// in order to restore them after the build completes.
func autoPin(ctx context.Context, moduleDirs []string, subcommand string, args []string) (*PinResult, error) {
	stateManager, found := stateManagerFromContext(ctx)
	if !found {
		return nil, ex.New("state manager not found in context")
	}
	ctx = withPinDiscoveryCache(ctx)
	moduleDirs = normalizeModuleDirs(moduleDirs)
	preflightOpts := PinOptions{Args: args, Subcommand: subcommand, ModuleDirs: moduleDirs, AutoPin: true}
	configs, unconfigured, err := discoverPinConfigs(moduleDirs)
	if err != nil {
		return nil, err
	}
	if err = preflightPinSource(ctx, configs, unconfigured, preflightOpts); err != nil {
		return nil, err
	}

	backupFiles, getBackupErr := getBackupFiles(ctx, buildDir(subcommand, args), moduleDirs)
	if getBackupErr != nil {
		return nil, getBackupErr
	}
	if trackErr := stateManager.TrackAll(backupFiles...); trackErr != nil {
		return nil, trackErr
	}

	pinResult, pinErr := Pin(ctx, PinOptions{
		Prune:      true,
		Args:       args,
		Subcommand: subcommand,
		ModuleDirs: moduleDirs,
		AutoPin:    true,
	})

	return pinResult, pinErr
}
