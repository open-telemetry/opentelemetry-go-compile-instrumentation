const (
	// overlayFileName is the overlay setup writes into the build directory.
	overlayFileName = "overlay.json"
	// importsFileName is the file the overlay adds to a package so the go
	// command sees the imports rules add to it.
	importsFileName = "otelc.imports"
	// overlaySourcesDir holds the files the overlay maps in.
	overlaySourcesDir = "overlay"
	// modReplaceDir holds the replacement directories of module cache
	// modules. They hold directories only; their files come from the overlay.
	modReplaceDir = "modreplace"
)

// overlayFile is the -overlay file format of the go command.
type overlayFile struct {
	Replace map[string]string `json:"Replace"`
}

// importsFileSource returns a Go file of package name that blank-imports
// every path in imports.
func importsFileSource(name string, imports []string) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by otelc. DO NOT EDIT.\n\npackage " + name + "\n\n")
	for _, imp := range slices.Sorted(slices.Values(imports)) {
		b.WriteString("import _ " + strconv.Quote(imp) + "\n")
	}
	return b.Bytes()
}

// buildImportOverlay writes the files the overlay maps in under buildDir and
// returns the overlay that makes the go command see every target's imports.
// A package in place gets otelc.imports.go in its own directory. A module
// cache module, which an overlay may not touch, is replaced in goModPath by
// a directory under buildDir whose files all come from the overlay.
func buildImportOverlay(targets []*importTarget, goModPath, buildDir string) (overlayFile, error) {
	o := overlayFile{Replace: make(map[string]string)}
	srcDir := filepath.Join(buildDir, overlaySourcesDir)
	if err := os.MkdirAll(srcDir, 0o755); err != nil {
		return o, ex.Wrapf(err, "creating %s", srcDir)
	}
	replaced := make(map[moduleRoot]string)
	for _, t := range targets {
		dir := t.Dir
		switch t.Kind {
		case kindRuntimeFile:
			continue
		case kindModCache:
			replaceDir, ok := replaced[t.Module]
			if !ok {
				var err error
				if replaceDir, err = mapModule(o, t.Module, buildDir); err != nil {
					return o, err
				}
				replaced[t.Module] = replaceDir
			}
			rel, err := filepath.Rel(t.Module.Dir, t.Dir)
			if err != nil {
				return o, ex.Wrapf(err, "locating %s in module %s", t.Dir, t.Module.Path)
			}
			dir = filepath.Join(replaceDir, rel)
		case kindInPlace:
		}
		name := importsFileName + ".go"
		if strings.HasSuffix(t.Name, "_test") {
			name = importsFileName + "_test.go"
		}
		target := filepath.Join(dir, name)
		src, err := writeOverlaySource(srcDir, target, importsFileSource(t.Name, t.Imports))
		if err != nil {
			return o, err
		}
		o.Replace[target] = src
	}
	if len(replaced) > 0 {
		src, err := replacedGoMod(goModPath, replaced, srcDir)
		if err != nil {
			return o, err
		}
		o.Replace[goModPath] = src
	}
	return o, nil
}

// mapModule maps every file of mod into a replacement directory under
// buildDir and creates that directory's tree on disk: cgo and asm run inside
// the package directory, so it has to exist.
func mapModule(o overlayFile, mod moduleRoot, buildDir string) (string, error) {
	escaped, err := module.EscapePath(mod.Path)
	if err != nil {
		return "", ex.Wrapf(err, "escaping module path %s", mod.Path)
	}
	replaceDir := filepath.Join(buildDir, modReplaceDir, filepath.FromSlash(escaped)+"@"+mod.Version)
	hasGoMod := false
	err = filepath.WalkDir(mod.Dir, func(path string, d fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		rel, _ := filepath.Rel(mod.Dir, path)
		if d.IsDir() {
			return os.MkdirAll(filepath.Join(replaceDir, rel), 0o755)
		}
		hasGoMod = hasGoMod || rel == "go.mod"
		o.Replace[filepath.Join(replaceDir, rel)] = path
		return nil
	})
	if err != nil {
		return "", ex.Wrapf(err, "mapping module %s", mod.Path)
	}
	if !hasGoMod {
		goMod := filepath.Join(replaceDir, "go.mod")
		src, err := writeOverlaySource(filepath.Join(buildDir, overlaySourcesDir), goMod,
			[]byte("module "+mod.Path+"\n"))
		if err != nil {
			return "", err
		}
		o.Replace[goMod] = src
	}
	return replaceDir, nil
}

// replacedGoMod writes a copy of goModPath that replaces each module in
// replaced with its replacement directory.
func replacedGoMod(goModPath string, replaced map[moduleRoot]string, srcDir string) (string, error) {
	data, err := os.ReadFile(goModPath)
	if err != nil {
		return "", ex.Wrapf(err, "reading %s", goModPath)
	}
	f, err := modfile.Parse(goModPath, data, nil)
	if err != nil {
		return "", ex.Wrapf(err, "parsing %s", goModPath)
	}
	for mod, dir := range replaced {
		// The build list names a module replaced by another module version by
		// its original path.
		oldPath := mod.Path
		for _, r := range f.Replace {
			if r.New.Path == mod.Path && r.New.Version == mod.Version {
				oldPath = r.Old.Path
			}
		}
		if err = f.AddReplace(oldPath, "", dir, ""); err != nil {
			return "", ex.Wrapf(err, "replacing %s in %s", oldPath, goModPath)
		}
	}
	f.Cleanup()
	out, err := f.Format()
	if err != nil {
		return "", ex.Wrapf(err, "formatting %s", goModPath)
	}
	return writeOverlaySource(srcDir, goModPath, out)
}

// writeOverlaySource writes content for the overlay entry target into srcDir,
// under a name derived from target so it is the same on every build.
func writeOverlaySource(srcDir, target string, content []byte) (string, error) {
	sum := sha256.Sum256([]byte(target))
	path := filepath.Join(srcDir, hex.EncodeToString(sum[:8])+"-"+filepath.Base(target))
	if err := os.WriteFile(path, content, 0o644); err != nil {
		return "", ex.Wrapf(err, "writing overlay file for %s", target)
	}
	return path, nil
}

// writeImportOverlay writes o as buildDir/overlay.json and returns its path.
// When o is empty it removes any overlay an earlier setup left and returns "".
func writeImportOverlay(o overlayFile, buildDir string) (string, error) {
	path := filepath.Join(buildDir, overlayFileName)
	if len(o.Replace) == 0 {
		if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
			return "", ex.Wrapf(err, "removing stale %s", path)
		}
		return "", nil
	}
	data, err := json.Marshal(o)
	if err != nil {
		return "", ex.Wrapf(err, "encoding overlay")
	}
	if err = os.WriteFile(path, data, 0o644); err != nil {
		return "", ex.Wrapf(err, "writing %s", path)
	}
	return path, nil
}

// mergeUserOverlay adds the entries of the user's overlay file at userPath to
// ours. The go command takes one -overlay, so the build passes the merged one.
// A path both overlays replace is an error.
func mergeUserOverlay(ours overlayFile, userPath string) (overlayFile, error) {
	if userPath == "" {
		return ours, nil
	}
	data, err := os.ReadFile(userPath)
	if err != nil {
		return ours, ex.Wrapf(err, "reading -overlay file %s", userPath)
	}
	var user overlayFile
	if err = json.Unmarshal(data, &user); err != nil {
		return ours, ex.Wrapf(err, "parsing -overlay file %s", userPath)
	}
	merged := overlayFile{Replace: make(map[string]string, len(ours.Replace)+len(user.Replace))}
	maps.Copy(merged.Replace, user.Replace)
	for from, to := range ours.Replace {
		if _, clash := merged.Replace[from]; clash {
			return ours, ex.Newf("the -overlay file %s replaces %s, which otelc also has to replace", userPath, from)
		}
		merged.Replace[from] = to
	}
	return merged, nil
}

// isOverlayFlag reports whether arg is an -overlay flag and whether its value
// is the next argument.
func isOverlayFlag(arg string) (bool, bool) {
	name := strings.TrimPrefix(strings.TrimPrefix(arg, "-"), "-")
	if name == "overlay" {
		return true, true
	}
	return strings.HasPrefix(name, "overlay="), false
}

// stripOverlayFlag removes -overlay flags from build arguments; arguments
// after -args go to the test binary and stay.
func stripOverlayFlag(args []string) []string {
	out := make([]string, 0, len(args))
	for i := 0; i < len(args); i++ {
		if args[i] == "-args" || args[i] == "--args" {
			return append(out, args[i:]...)
		}
		if ok, takesNext := isOverlayFlag(args[i]); ok {
			if takesNext {
				i++
			}
			continue
		}
		out = append(out, args[i])
	}
	return out
}

// userOverlayPath returns the absolute path of the -overlay file the user
// gave on the command line or in GOFLAGS, or "". A relative path resolves
// against dir, the directory the go command runs in.
func userOverlayPath(args []string, dir string) string {
	find := func(args []string) string {
		value := ""
		for i := 0; i < len(args); i++ {
			if args[i] == "-args" || args[i] == "--args" {
				break
			}
			ok, takesNext := isOverlayFlag(args[i])
			switch {
			case ok && takesNext && i+1 < len(args):
				value = args[i+1]
				i++
			case ok && !takesNext:
				_, value, _ = strings.Cut(args[i], "=")
			}
		}
		return value
	}
	path := find(args)
	if path == "" {
		path = find(util.SplitGoflags(os.Getenv("GOFLAGS")))
	}
	if path == "" || filepath.IsAbs(path) {
		return path
	}
	return filepath.Join(dir, path)
}

// prepareImportOverlay writes the overlay that makes the go command see the
// imports the matched rules add, merged with the user's overlay. It returns
// the overlay path ("" when nothing needs one) and, keyed by directory, the
// imports of file-target packages, which go into their otelc.runtime.go.
func (sp *setupPhase) prepareImportOverlay(
	matched []*rule.InstRuleSet,
	goModPath, goroot, gomodcache, userOverlay, buildDir string,
) (string, map[string][]string, error) {
	targets, err := sp.importTargets(matched, goroot, gomodcache)
	if err != nil {
		return "", nil, err
	}
	runtimeImports := make(map[string][]string)
	for _, t := range targets {
		if t.Kind == kindRuntimeFile {
			runtimeImports[t.Dir] = t.Imports
		}
	}
	o, err := buildImportOverlay(targets, goModPath, buildDir)
	if err != nil {
		return "", nil, err
	}
	if len(o.Replace) > 0 {
		if o, err = mergeUserOverlay(o, userOverlay); err != nil {
			return "", nil, err
		}
	}
	path, err := writeImportOverlay(o, buildDir)
	return path, runtimeImports, err
}

// withImportOverlay points the instrumented build at the overlay setup wrote,
// if any. The overlay already holds the user's entries, so the user's own
// -overlay flag is dropped; a command-line flag would win over goFlags.
func withImportOverlay(args, goFlags []string) ([]string, []string) {
	path := filepath.Join(util.GetBuildTempDir(), overlayFileName)
	if !util.PathExists(path) {
		return args, goFlags
	}
	args = append([]string{args[0]}, stripOverlayFlag(args[1:])...)
	return args, append(goFlags, "-overlay="+path)
}
